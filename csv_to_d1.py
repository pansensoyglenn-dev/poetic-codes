#!/usr/bin/env python3
"""
csv_to_d1.py - turn the Supabase articles CSV export into SQL for Cloudflare D1.

Usage:
    python csv_to_d1.py articles_rows.csv            # writes import_articles.sql + supabase_media_urls.txt
Then:
    npx wrangler d1 execute <YOUR_D1_DATABASE_NAME> --remote --file=import_articles.sql

Safe to run twice: an article is inserted only if no article with the same
title + date exists, and long bodies are appended in guarded chunks.
Media links are left unchanged for now (they still point at Supabase);
supabase_media_urls.txt lists every Supabase file to move to R2 later.
"""
import csv, re, sys

csv.field_size_limit(10**9)
SRC = sys.argv[1] if len(sys.argv) > 1 else "articles_rows.csv"
CHUNK_BYTES = 60000          # stay far below D1's 100 KB statement limit

def q(v):                    # SQL string literal (or NULL)
    return "NULL" if v in (None, "") else "'" + v.replace("'", "''") + "'"

def chunks(text):
    out, cur, size = [], [], 0
    for ch in text:
        b = len(ch.encode())
        if size + b > CHUNK_BYTES:
            out.append("".join(cur)); cur, size = [], 0
        cur.append(ch); size += b
    if cur: out.append("".join(cur))
    return out or [""]

rows = list(csv.DictReader(open(SRC, encoding="utf-8", newline="")))
sql = ["-- generated by csv_to_d1.py", ""]
urls = set()
SB = re.compile(r"https://[a-z0-9]+\.supabase\.co/storage/v1/object/public/[^\s\"'<>)]+")
for r in rows:
    title, date = r["title"].strip(), r["date"].strip()[:10]
    where = f"title={q(title)} AND date={q(date)}"
    parts = chunks(r["content"])
    sql.append(
        "INSERT INTO articles (title,category,date,content_type,body,summary,tags,photo_url,video_url,github_url,page_url,deploy_status)\n"
        f"SELECT {q(title)},{q(r['category'])},{q(date)},{q(r['content_type'] or 'html')},{q(parts[0]) if parts[0] else chr(39)*2},"
        f"{q(r['excerpt'])},{q(r['tags'] or '[]')},{q(r['photo_url'])},{q(r['video_url'])},{q(r['github_url'])},{q(r['page_url'])},'{{}}'\n"
        f"WHERE NOT EXISTS (SELECT 1 FROM articles WHERE {where});")
    done = len(parts[0])
    for p in parts[1:]:
        sql.append(f"UPDATE articles SET body = body || {q(p)} WHERE {where} AND length(body) = {done};")
        done += len(p)
    sql.append("")
    for k in ("photo_url", "video_url", "content"):
        urls |= set(SB.findall(r[k]))

open("import_articles.sql", "w", encoding="utf-8").write("\n".join(sql))
open("supabase_media_urls.txt", "w", encoding="utf-8").write("\n".join(sorted(urls)) + "\n")
print(f"{len(rows)} articles -> import_articles.sql ; {len(urls)} Supabase media URLs -> supabase_media_urls.txt")
